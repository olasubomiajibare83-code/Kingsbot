# GENERATE RESPONSE
# ============================================================

def generate_response(user_message):

    # --------------------------------------------------------
    # MEMORY COMMANDS
    # --------------------------------------------------------

    forgotten = handle_forgetting(
        user_message
    )

    if forgotten:

        set_transparency(
            "Memory system",
            "High",
            "This answer came directly from a memory command."
        )

        return forgotten

    detect_name(
        user_message
    )

    detect_student_level(
        user_message
    )

    remember_information(
        user_message
    )

    # --------------------------------------------------------
    # EMOTION
    # --------------------------------------------------------

    emotion = detect_emotion(
        user_message
    )

    st.session_state.last_emotion = emotion

    tone_instruction, tone_name = get_tone_instruction(
        emotion
    )

    st.session_state.last_tone = tone_name

    # --------------------------------------------------------
    # VERIFIED FACTS FIRST
    # --------------------------------------------------------

    fact = verified_fact(
        user_message
    )

    if fact:

        set_transparency(
            "KingsBot verified fact",
            "High",
            "This answer came from a built-in verified fact."
        )

        proactive_guidance(
            user_message
        )

        return fact

    # --------------------------------------------------------
    # CURRENT INFORMATION
    # --------------------------------------------------------

    current_info = None

    if is_current_question(
        user_message
    ):

        current_info = current_information_search(
            user_message
        )

    # --------------------------------------------------------
    # EDUCATION LEVEL
    # --------------------------------------------------------

    if st.session_state.student_level:

        education_instruction = (
            "The user's education level is "
            + st.session_state.student_level
            + ". Match the explanation to that level. "
            "Do not give university-level material to a "
            "younger student unless they specifically ask "
            "for advanced material."
        )

    else:

        education_instruction = (
            "The user's education level is unknown. "
            "Use a clear general level."
        )

    # --------------------------------------------------------
    # PERSONAL MEMORY
    # --------------------------------------------------------

    memory_text = build_memory()

    # --------------------------------------------------------
    # PATTERNS
    # --------------------------------------------------------

    patterns = detect_patterns()

    # --------------------------------------------------------
    # SYSTEM PROMPT
    # --------------------------------------------------------

    system_prompt = (

        "You are KingsBot, a helpful and intelligent AI assistant.\n\n"

        "CURRENT DATE:\n"
        "Today is August 25, 2026.\n"
        "2026 is the CURRENT year.\n"
        "2026 is NOT the future.\n"
        "Never describe 2026 itself as a future year.\n"
        "Only dates after August 25, 2026 are future dates.\n\n"

        "IMPORTANT:\n"
        "Your internal training knowledge may be older than 2026. "
        "Therefore, when current information is supplied below, "
        "use that information instead of guessing from old memory.\n\n"

        "Do not invent facts.\n"
        "If information is uncertain, say so.\n"
        "Answer factual questions directly.\n"
        "For calculations, show useful steps.\n"
        "For coding questions, give correct usable code.\n\n"

        + education_instruction
        + "\n\n"

        + tone_instruction
        + "\n\n"

        "You can help with:\n"
        "- Primary school\n"
        "- JSS1, JSS2 and JSS3\n"
        "- SS1, SS2 and SS3\n"
        "- University subjects\n"
        "- Mathematics\n"
        "- Science\n"
        "- Coding\n"
        "- Technology\n"
        "- History\n"
        "- Geography\n"
        "- General knowledge\n"
        "- Everyday questions\n"
    )

    # --------------------------------------------------------
    # MEMORY
    # --------------------------------------------------------

    system_prompt += (
        "\n\nUSER MEMORY:\n"
        + memory_text
    )

    # --------------------------------------------------------
    # PATTERNS
    # --------------------------------------------------------

    if patterns:

        system_prompt += (
            "\n\nPATTERNS:\n"
            + "\n".join(patterns)
        )

    # --------------------------------------------------------
    # CURRENT WEB INFORMATION
    # --------------------------------------------------------

    if current_info:

        system_prompt += (
            "\n\nCURRENT INFORMATION RETRIEVED:\n"
            + current_info
            + "\n\n"
            "Use this information when answering the current "
            "question. Do not replace it with an older guess."
        )

    # --------------------------------------------------------
    # BUILD CHAT
    # --------------------------------------------------------

    messages = [
        {
            "role": "system",
            "content": system_prompt
        }
    ]

    # Keep recent conversation so the prompt does not become huge.
    messages.extend(
        st.session_state.messages[-12:]
    )

    messages.append(
        {
            "role": "user",
            "content": user_message
        }
    )

    # --------------------------------------------------------
    # TOKENIZE
    # --------------------------------------------------------

    text = tokenizer.apply_chat_template(
        messages,
        tokenize=False,
        add_generation_prompt=True
    )

    model_inputs = tokenizer(
        [text],
        return_tensors="pt",
        truncation=True,
        max_length=2048
    ).to(model.device)

    # --------------------------------------------------------
    # GENERATE
    # --------------------------------------------------------

    with torch.no_grad():

        generated_ids = model.generate(
            **model_inputs,
            max_new_tokens=512,
            do_sample=True,
            temperature=0.6,
            top_p=0.9,
            repetition_penalty=1.05,
            pad_token_id=tokenizer.eos_token_id
        )

    # --------------------------------------------------------
    # REMOVE PROMPT
    # --------------------------------------------------------

    generated_ids = [
        output_ids[len(input_ids):]
        for input_ids, output_ids in zip(
            model_inputs.input_ids,
            generated_ids
        )
    ]

    # --------------------------------------------------------
    # DECODE
    # --------------------------------------------------------

    response = tokenizer.batch_decode(
        generated_ids,
        skip_special_tokens=True
    )[0].strip()

    if not response:

        response = (
            "I couldn't generate an answer. "
            "Please try again."
        )

    # --------------------------------------------------------
    # TRANSPARENCY
    # --------------------------------------------------------

    if current_info:

        set_transparency(
            "Current-information lookup + Qwen",
            "High",
            "Current information was retrieved before generating the answer."
        )

    else:

        set_transparency(
            "Qwen2.5-0.5B-Instruct",
            "Medium",
            "No external current information was available for this question."
        )

    proactive_guidance(
        user_message
    )

    return response


