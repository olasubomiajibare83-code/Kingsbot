def known_fact(question):

    lower = question.lower()

    if (
        "messi" in lower
        and "world cup" in lower
    ):

        return (
            "Lionel Messi has won the FIFA World Cup "
            "once. He won the 2022 FIFA World Cup "
            "with Argentina."
        )

    if (
        "what year is it" in lower
        or "which year is it" in lower
    ):

        return (
            "It is 2026. Today is August 25, 2026."
        )

    if (
        "what is today's date" in lower
        or "what date is it" in lower
    ):

        return (
            "Today is August 25, 2026."
        )

    return None


