def load_persistent_memory():

    try:

        if os.path.exists(MEMORY_FILE):

            with open(
                MEMORY_FILE,
                "r",
                encoding="utf-8"
            ) as file:

                data = json.load(file)

            if not isinstance(data, dict):

                return DEFAULT_MEMORY.copy()

            for key in DEFAULT_MEMORY:

                if key not in data:

                    data[key] = DEFAULT_MEMORY[key]

            return data

    except Exception:

        return DEFAULT_MEMORY.copy()


