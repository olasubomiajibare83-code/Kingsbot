def wikipedia_lookup(question):

    try:

        search = requests.get(

            "https://en.wikipedia.org/w/api.php",

            params={
                "action": "query",
                "list": "search",
                "srsearch": question,
                "format": "json",
                "utf8": 1,
                "srlimit": 3
            },

            headers={
                "User-Agent": "KingsBot/1.0"
            },

            timeout=8
        )

        search.raise_for_status()

        results = (
            search.json()
            .get("query", {})
            .get("search", [])
        )


        summaries = []


        for item in results:

            title = item.get(
                "title"
            )

            if not title:
                continue


            page = requests.get(

                "https://en.wikipedia.org/api/rest_v1/page/summary/"
                + requests.utils.quote(title),

                headers={
                    "User-Agent": "KingsBot/1.0"
                },

                timeout=8
            )


            if page.ok:

                summary = page.json().get(
                    "extract"
                )

                if summary:

                    summaries.append(
                        f"{title}: {summary}"
                    )


        if summaries:

            return "\n\n".join(
                summaries[:3]
            )


    except Exception:
        pass


    return None


