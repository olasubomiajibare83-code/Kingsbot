def needs_current_information(text):

    lower = text.lower()

    current_words = [
        "today",
        "now",
        "currently",
        "latest",
        "recent",
        "recently",
        "this year",
        "this month",
        "this week",
        "2026",
        "news"
    ]

    for word in current_words:

        if word in lower:

            return True

    return False


# ============================================================
# CURRENT INFORMATION
# ============================================================

def get_current_information(question):

    results = []

    try:

        response = requests.get(
            "https://en.wikipedia.org/w/api.php",
            params={
                "action": "query",
                "list": "search",
                "srsearch": question,
                "format": "json",
                "utf8": "1",
                "srlimit": 3
            },
            headers={
                "User-Agent": "KingsBotAI/1.0"
            },
            timeout=8
        )

        response.raise_for_status()

        data = response.json()

        items = (
            data
            .get("query", {})
            .get("search", [])
        )

        for item in items:

            title = item.get("title")

            if not title:
                continue

            try:

                page = requests.get(
                    "https://en.wikipedia.org/api/rest_v1/page/summary/"
                    + requests.utils.quote(title),
                    headers={
                        "User-Agent": "KingsBotAI/1.0"
                    },
                    timeout=8
                )

                page.raise_for_status()

                page_data = page.json()

                extract = page_data.get(
                    "extract"
                )

                if extract:

                    results.append(
                        title
                        + ":\n"
                        + extract
                    )

            except Exception:

                continue

    except Exception:

        pass

    if not results:

        return None

    return "\n\n".join(
        results[:3]
    )


