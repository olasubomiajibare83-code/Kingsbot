def remember_information(text):

    lower = text.lower()

    triggers = [
        "remember that",
        "remember this",
        "please remember",
        "keep this in mind",
        "save this"
    ]

    for trigger in triggers:

        if trigger in lower:

            position = lower.find(trigger)

            memory = text[
                position + len(trigger):
            ].strip(" :,-")

            if memory:

                if memory not in (
                    st.session_state.personal_memory
                ):

                    st.session_state.personal_memory.append(
                        memory
                    )

                    save_persistent_memory()

                return memory

    return None


