def recognize_topic(text):

    lower = text.lower()

    categories = {

        "coding": [
            "code",
            "python",
            "program",
            "programming",
            "streamlit",
            "app",
            "software"
        ],

        "mathematics": [
            "math",
            "calculate",
            "equation",
            "algebra",
            "geometry",
            "calculus"
        ],

        "science": [
            "science",
            "biology",
            "chemistry",
            "physics"
        ],

        "sports": [
            "football",
            "soccer",
            "world cup",
            "player",
            "messi"
        ],

        "education": [
            "school",
            "class",
            "jss",
            "sss",
            "primary",
            "university"
        ]

    }


    for category, words in categories.items():

        for word in words:

            if word in lower:

                return category


    return "general"


def update_topic(text):

    topic = recognize_topic(text)

    st.session_state.last_topic = topic

    if topic not in st.session_state.topic_pattern:

        st.session_state.topic_pattern.append(
            topic
        )

        save_memory()

    return topic


# ============================================================
# PROACTIVE GLUE
# ============================================================

def proactive_glue(text):

    topic = recognize_topic(text)

    previous = st.session_state.last_topic


    if previous == topic:

        return (
            "The user may be continuing the same topic. "
            "Use the relevant recent context."
        )


    if previous and previous != topic:

        return (
            "The user appears to have changed topics. "
            "Focus on the new question."
        )


    return (
        "Understand the user's goal and provide "
        "the most useful next step when appropriate."
    )


