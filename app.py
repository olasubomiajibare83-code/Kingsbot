# WIKIPEDIA LOOKUP
# ============================================================

def web_lookup(question):
    try:
        response = requests.get(
            "https://en.wikipedia.org/w/api.php",
            params={
                "action": "query",
                "list": "search",
                "srsearch": question,
                "format": "json",
                "utf8": "1",
                "srlimit": 3,
            },
            headers={
                "User-Agent": "KingsBotAI/1.0",
            },
            timeout=8,
        )

        response.raise_for_status()

        results = (
            response.json()
            .get("query", {})
            .get("search", [])
        )

        information = []

        for result in results:
            title = result.get("title")

            if not title:
                continue

            try:
                page = requests.get(
                    "https://en.wikipedia.org/api/rest_v1/page/summary/"
                    + requests.utils.quote(title),
                    headers={
                        "User-Agent": "KingsBotAI/1.0",
                    },
                    timeout=8,
                )

                if page.ok:
                    summary = page.json().get(
                        "extract"
                    )

                    if summary:
                        information.append(
                            title
                            + ": "
                            + summary
                        )

            except Exception:
                continue

        if information:
            return "\n\n".join(
                information[:3]
            )

    except Exception:
        pass

    return None


