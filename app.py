def needs_current_lookup(text):
    lower = text.lower()

    return any(
        word in lower
        for word in [
            "today",
            "right now",
            "currently",
            "latest",
            "recent",
            "this year",
            "this month",
            "this week",
            "news",
            "2026",
        ]
    )


def current_lookup(question):
    try:
        response = requests.get(
            "https://en.wikipedia.org/w/api.php",
            params={
                "action": "query",
                "list": "search",
                "srsearch": question,
                "format": "json",
                "utf8": "1",
                "srlimit": 3,
            },
            headers={
                "User-Agent": "KingsBotAI/3.0"
            },
            timeout=6,
        )

        response.raise_for_status()

        results = []

        for item in (
            response.json()
            .get("query", {})
            .get("search", [])
        ):
            title = item.get("title")

            if not title:
                continue

            try:
                page = requests.get(
                    "https://en.wikipedia.org/api/rest_v1/page/summary/"
                    + requests.utils.quote(title),
                    headers={
                        "User-Agent": "KingsBotAI/3.0"
                    },
                    timeout=6,
                )

                page.raise_for_status()

                summary = page.json().get("extract")

                if summary:
                    results.append(
                        title
                        + ":\n"
                        + summary
                    )

            except Exception:
                continue

        if results:
            return "\n\n".join(results[:3])

    except Exception:
        pass

    return None


