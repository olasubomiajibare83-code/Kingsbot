def reasoning_instruction(text):

    topic = recognize_pattern(text)

    if topic == "mathematics":

        return (
            "Work through the mathematics carefully. "
            "Check arithmetic and logic before answering. "
            "Give the useful steps rather than guessing."
        )

    if topic == "coding":

        return (
            "Analyze the coding request first. "
            "Check imports, indentation, variables, "
            "functions and dependencies before producing code."
        )

    if topic == "education":

        return (
            "Identify the learner's education level. "
            "Teach progressively and do not accidentally "
            "replace a junior-school curriculum with "
            "university-level material."
        )

    return (
        "Analyze the question before answering. "
        "For multi-part problems, handle each important "
        "part logically. Do not expose private chain-of-thought."
    )


