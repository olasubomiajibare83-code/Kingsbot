    st.divider()

    if st.button("🗑️ Clear conversation"):
        st.session_state.messages = []
        st.session_state.last_user_question = ""
        st.session_state.last_response = ""
        st.rerun()

    if st.button("🧹 Forget personal memory"):
        st.session_state.user_name = None
        st.session_state.student_level = None
        st.session_state.personal_memory = []
        st.session_state.preferences = []
        save_memory()

        st.success("Personal memory cleared.")
        st.rerun()

    st.divider()

    st.caption("Model: " + MODEL_NAME)
    st.caption("Groq API key is stored securely in Streamlit Secrets.")
