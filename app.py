def remember_from_text(text):

    match = re.search(
        r"\b(?:my name is|call me)\s+([A-Za-z][A-Za-z '\-]{1,39})",
        text,
        re.IGNORECASE
    )

    if match:

        st.session_state.name = (
            match.group(1).strip()
        )

        save_memory()


    match = re.search(
        r"\b(?:remember that|remember this|save this)"
        r"\s*[:,-]?\s*(.+)",
        text,
        re.IGNORECASE
    )

    if match:

        fact = match.group(1).strip()

        if fact and fact not in st.session_state.facts:

            st.session_state.facts.append(
                fact
            )

            save_memory()

        return fact

    return None


