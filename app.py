# ============================================================
# GENERATE RESPONSE
# ============================================================

def generate_response(user_message):

    # Memory
    detect_name(user_message)
    detect_student_level(user_message)
    remember_information(user_message)

    # Forgetting
    forgotten = forget_information(
        user_message
    )

    if forgotten:

        st.session_state.source = "Memory system"
        st.session_state.confidence = "High"
        st.session_state.reason = (
            "This was a memory-management command."
        )

        return forgotten

    # Emotion and tone
    emotion = detect_emotion(
        user_message
    )

    st.session_state.emotion = emotion

    tone_text, tone_name = tone_instruction(
        emotion
    )

    st.session_state.tone = tone_name

    # Known facts
    fact = known_fact(
        user_message
    )

    if fact:

        st.session_state.source = "Verified KingsBot fact"
        st.session_state.confidence = "High"
        st.session_state.reason = (
            "This answer uses a built-in verified fact."
        )

        return fact

    # Current information
    current_info = None

    if needs_current_information(
        user_message
    ):

        current_info = get_current_information(
            user_message
        )

    # Education level
    if st.session_state.student_level:

        education = (
            "The user is "
            + st.session_state.student_level
            + ". Match the explanation to this level. "
            "Do not give advanced university material to "
            "a younger student unless they specifically "
            "ask for advanced material."
        )

    else:

        education = (
            "The user's education level is unknown. "
            "Use a clear general level."
        )

    # System instruction
    system_prompt = (

        "You are KingsBot, a helpful and intelligent AI assistant.\n\n"

        "CURRENT DATE:\n"
        "Today is August 25, 2026.\n"
        "2026 is the current year, not the future.\n\n"

        "IMPORTANT:\n"
        "Your model knowledge may be older than 2026. "
        "If current information is supplied below, "
        "use it instead of guessing.\n\n"

        "Never invent facts.\n"
        "If you do not know something, say so.\n"
        "Answer directly and clearly.\n"
        "For school questions, teach step by step.\n"
        "For coding questions, provide usable code.\n\n"

        + education
        + "\n\n"

        + tone_text
        + "\n\n"

        "Personal memory:\n"
        + build_memory()
    )

    if current_info:

        system_prompt += (
            "\n\nCURRENT INFORMATION:\n"
            + current_info
            + "\n\nUse this information for the answer."
        )

    # Recent conversation
    messages = [
        {
            "role": "system",
            "content": system_prompt
        }
    ]

    messages.extend(
        st.session_state.messages[-12:]
    )

    messages.append(
        {
            "role": "user",
            "content": user_message
        }
    )

    # Tokenize
    text = tokenizer.apply_chat_template(
        messages,
        tokenize=False,
        add_generation_prompt=True
    )

    model_inputs = tokenizer(
        [text],
        return_tensors="pt",
        truncation=True,
        max_length=2048
    ).to(model.device)

    # Generate
    with torch.no_grad():

        generated_ids = model.generate(
            **model_inputs,
            max_new_tokens=512,
            do_sample=True,
            temperature=0.6,
            top_p=0.9,
            repetition_penalty=1.05,
            pad_token_id=tokenizer.eos_token_id
        )

    # Remove prompt
    generated_ids = [
        output_ids[len(input_ids):]
        for input_ids, output_ids in zip(
            model_inputs.input_ids,
            generated_ids
        )
    ]

    # Decode
    response = tokenizer.batch_decode(
        generated_ids,
        skip_special_tokens=True
    )[0].strip()

    if not response:

        response = (
            "I couldn't generate an answer. "
            "Please try again."
        )

    # Transparency
    if current_info:

        st.session_state.source = (
            "Current-information lookup + Qwen"
        )

        st.session_state.confidence = "High"

        st.session_state.reason = (
            "Current information was retrieved before "
            "generating this answer."
        )

    else:

        st.session_state.source = (
            "Qwen2.5-0.5B-Instruct"
        )

        st.session_state.confidence = "Medium"

        st.session_state.reason = (
            "No external current-information lookup "
            "was needed for this question."
        )

    return response


