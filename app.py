def ask_ai(user_text, retrieved=None):
    if not token_available():
        return (
            "Your KingsBot AI brain is configured to use "
            "Hugging Face, but HF_TOKEN is not available "
            "in Streamlit Secrets."
        )

    system_prompt = build_system_prompt(
        retrieved
    )

    messages = [
        {
            "role": "system",
            "content": system_prompt,
        }
    ]

    # IMPORTANT:
    # The current user message has already been added
    # to session state before this function is called.
    # Therefore we use the existing history directly
    # and DO NOT append user_text a second time.

    for message in st.session_state.messages[-14:]:
        role = message.get("role")

        if role not in (
            "user",
            "assistant",
        ):
            continue

        content = message.get(
            "content",
            "",
        )

        if not content:
            continue

        messages.append(
            {
                "role": role,
                "content": content,
            }
        )

    payload = {
        "model": CHAT_MODEL,
        "messages": messages,
        "temperature": 0.6,
        "max_tokens": 900,
    }

    try:
        response = requests.post(
            "https://router.huggingface.co/v1/chat/completions",
            headers=api_headers(),
            json=payload,
            timeout=90,
        )

        response.raise_for_status()

        data = response.json()

        choices = data.get(
            "choices",
            [],
        )

        if not choices:
            return (
                "The AI model did not return an answer."
            )

        message = choices[0].get(
            "message",
            {},
        )

        answer = message.get(
            "content",
            "",
        )

        if not answer:
            return (
                "The AI model returned an empty answer."
            )

        answer = answer.strip()

        if retrieved:
            st.session_state.source = (
                "Qwen AI + retrieved information"
            )
            st.session_state.confidence = (
                "Medium-High"
            )
            st.session_state.reason = (
                "The AI used retrieved information "
                "along with the conversation."
            )
        else:
            st.session_state.source = (
                "Qwen AI + memory + conversation"
            )
            st.session_state.confidence = "Medium"
            st.session_state.reason = (
                "The answer was generated by the "
                "Qwen AI model using the conversation "
                "and available memory."
            )

        return answer

    except requests.exceptions.Timeout:
        st.session_state.confidence = "Low"

        return (
            "The Hugging Face AI service took too long "
            "to respond. Please try again."
        )

    except requests.exceptions.HTTPError:
        st.session_state.confidence = "Low"

        try:
            details = response.json()
        except Exception:
            details = response.text

        return (
            "Hugging Face returned an error:\n\n"
            + str(details)
        )

    except requests.exceptions.RequestException as exc:
        st.session_state.confidence = "Low"

        return (
            "I could not connect to the AI service.\n\n"
            + str(exc)
        )

    except Exception as exc:
        st.session_state.confidence = "Low"

        return (
            "KingsBot encountered an error:\n\n"
            + str(exc)
        )


