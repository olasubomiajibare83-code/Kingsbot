def default_memory():
    return {
        "name": None,
        "education_level": None,
        "facts": [],
        "preferences": []
    }


def load_memory():
    memory = default_memory()

    try:
        if os.path.exists(MEMORY_FILE):
            with open(
                MEMORY_FILE,
                "r",
                encoding="utf-8"
            ) as file:
                saved = json.load(file)

            if isinstance(saved, dict):
                for key in memory:
                    if key in saved:
                        memory[key] = saved[key]

    except Exception:
        pass

    return memory


def save_memory():
    memory = {
        "name": st.session_state.name,
        "education_level": st.session_state.education_level,
        "facts": st.session_state.facts[-50:],
        "preferences": st.session_state.preferences[-30:]
    }

    try:
        with open(
            MEMORY_FILE,
            "w",
            encoding="utf-8"
        ) as file:
            json.dump(
                memory,
                file,
                indent=2,
                ensure_ascii=False
            )
    except Exception:
        pass


