def recognize_pattern(text):

    lower = text.lower()

    categories = {

        "coding": [
            "code",
            "python",
            "program",
            "programming",
            "streamlit",
            "app",
            "software"
        ],

        "mathematics": [
            "math",
            "calculate",
            "equation",
            "algebra",
            "geometry",
            "calculus"
        ],

        "science": [
            "science",
            "biology",
            "chemistry",
            "physics"
        ],

        "sports": [
            "football",
            "soccer",
            "world cup",
            "player",
            "messi"
        ],

        "education": [
            "school",
            "class",
            "jss",
            "sss",
            "primary",
            "university"
        ]
    }

    for category, words in categories.items():

        for word in words:

            if word in lower:

                return category

    return "general"


def update_pattern(text):

    topic = recognize_pattern(text)

    st.session_state.last_topic = topic

    if topic not in st.session_state.topic_pattern:

        st.session_state.topic_pattern.append(
            topic
        )

        save_persistent_memory()

    return topic


# ============================================================
# PROACTIVE GLUE THINKING
# ============================================================

def proactive_glue(text):

    topic = recognize_pattern(text)

    previous = st.session_state.last_topic

    if previous == topic:

        return (
            "The user appears to be continuing the "
            "same topic. Use relevant context from "
            "the recent conversation."
        )

    if previous and previous != topic:

        return (
            "The user appears to have changed topics. "
            "Focus on the new question and do not force "
            "unrelated previous information into the answer."
        )

    return (
        "Understand the user's actual goal. "
        "If there is an obvious useful next step, "
        "offer it briefly."
    )


# ============================================================
# MULTI-STEP REASONING
