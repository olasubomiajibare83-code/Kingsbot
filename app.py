def remember_information(text):

    lower = text.lower()

    triggers = [
        "remember that",
        "remember this",
        "please remember",
        "save this"
    ]

    for trigger in triggers:

        if trigger in lower:

            position = lower.find(trigger)

            information = text[
                position + len(trigger):
            ].strip(" :,-")

            if information:

                if information not in (
                    st.session_state.personal_memory
                ):

                    st.session_state.personal_memory.append(
                        information
                    )

                    save_memory()

            return information

    return None


