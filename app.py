def play_voice_automatically(audio_bytes):
    if not audio_bytes:
        return

    try:
        audio_base64 = base64.b64encode(
            audio_bytes
        ).decode("utf-8")

        components.html(
            f"""
            <audio
                id="kingsbot-auto-voice"
                autoplay
                controls
                style="width:100%;"
            >
                <source
                    src="data:audio/mp3;base64,{audio_base64}"
                    type="audio/mpeg"
                >
            </audio>

            <script>
                const player =
                    document.getElementById(
                        "kingsbot-auto-voice"
                    );

                if (player) {{
                    player.play().catch(
                        function(error) {{
                            console.log(
                                "Browser blocked autoplay.",
                                error
                            );
                        }}
                    );
                }}
            </script>
            """,
            height=75,
        )

    except Exception:
        pass


