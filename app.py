def tone_instruction(emotion):

    if emotion == "frustrated":

        return (
            "Be calm, respectful and direct.",
            "Calm and direct"
        )

    if emotion == "sad":

        return (
            "Be warm, kind and supportive.",
            "Warm and supportive"
        )

    if emotion == "confused":

        return (
            "Explain things slowly and step by step.",
            "Simple and step-by-step"
        )

    if emotion == "worried":

        return (
            "Be reassuring and practical.",
            "Reassuring and practical"
        )

    if emotion == "happy":

        return (
            "Be friendly and positive.",
            "Friendly and positive"
        )

    return (
        "Use a natural, friendly and clear tone.",
        "Natural and friendly"
    )


