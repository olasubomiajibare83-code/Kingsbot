def ask_ai(user_text, retrieved=None):
    if not has_token():
        st.session_state.source = "AI connection"
        st.session_state.confidence = "Unavailable"
        st.session_state.reason = (
            "HF_TOKEN has not been added to the Space Secrets."
        )

        return (
            "KingsBot is loaded, but its AI brain is not connected yet. "
            "Add HF_TOKEN to your Hugging Face Space Secrets."
        )


    messages = [
        {
            "role": "system",
            "content": build_system_prompt(
                retrieved
            )
        }
    ]


    messages.extend(
        st.session_state.messages[-12:]
    )


    messages.append(
        {
            "role": "user",
            "content": user_text
        }
    )


    payload = {
        "model": CHAT_MODEL,
        "messages": messages,
        "temperature": 0.6,
        "max_tokens": 700
    }


    try:
        response = requests.post(
            "https://router.huggingface.co/v1/chat/completions",
            headers=hf_headers(
                "application/json"
            ),
            json=payload,
            timeout=120
        )

        response.raise_for_status()

        data = response.json()

        choices = data.get(
            "choices",
            []
        )

        if not choices:
            raise ValueError(
                "The AI returned no answer."
            )

        answer = (
            choices[0]
            .get("message", {})
            .get("content", "")
            .strip()
        )

        if not answer:
            raise ValueError(
                "The AI returned an empty answer."
            )


        if retrieved:
            st.session_state.source = (
                "AI model + current information"
            )
            st.session_state.confidence = "Medium-High"
            st.session_state.reason = (
                "Additional retrieved information "
                "was supplied to the AI."
            )

        else:
            st.session_state.source = (
                "AI model + memory + conversation"
            )
            st.session_state.confidence = "Medium"
            st.session_state.reason = (
                "Generated by the AI using conversation "
                "and saved memory."
            )


        return answer


    except requests.exceptions.Timeout:
        st.session_state.confidence = "Low"
        st.session_state.reason = (
            "The AI service timed out."
        )

        return (
            "The AI service took too long to respond. "
            "Please try again."
        )


    except requests.exceptions.HTTPError:
        st.session_state.confidence = "Low"
        st.session_state.reason = (
            "The AI service returned an HTTP error."
        )

        try:
            details = response.json()
            message = json.dumps(
                details,
                indent=2
            )
        except Exception:
            message = response.text

        return (
            "The AI service returned an error:\n\n"
            + message
        )


    except Exception as error:
        st.session_state.confidence = "Low"
        st.session_state.reason = (
            "An unexpected AI error occurred."
        )

        return (
            "KingsBot encountered an error:\n\n"
            + str(error)
        )


