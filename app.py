def conversation_file():
    lines = [
        "KINGSBOT AI CONVERSATION",
        "=" * 50,
        "Date: " + CURRENT_DATE,
        "",
    ]

    for message in st.session_state.messages:
        role = message.get(
            "role",
            "unknown",
        ).upper()

        content = message.get(
            "content",
            "",
        )

        lines.append(
            role + ":"
        )

        lines.append(
            content
        )

        lines.append("")

    return "\n".join(lines)


# ============================================================
# PROCESS USER MESSAGE
# ============================================================

def process_user_message(user_text):
    forgotten = handle_forgetting(
        user_text
    )

    if forgotten:
        return forgotten

    remember_user_information(
        user_text
    )

    detect_education_level(
        user_text
    )

    st.session_state.emotion = (
        detect_emotion(user_text)
    )

    st.session_state.tone = (
        choose_tone(
            st.session_state.emotion
        )
    )

    st.session_state.topic = (
        detect_topic(user_text)
    )

    retrieved = None

    if needs_current_information(
        user_text
    ):
        retrieved = web_lookup(
            user_text
        )

    return ask_ai(
        user_text,
        retrieved,
    )


