def needs_current_information(text):

    lower = text.lower()

    words = [
        "today",
        "right now",
        "currently",
        "latest",
        "recent",
        "this year",
        "this month",
        "this week",
        "2026",
        "news"
    ]

    return any(
        word in lower
        for word in words
    )


def get_current_information(question):

    try:

        response = requests.get(
            "https://en.wikipedia.org/w/api.php",

            params={
                "action": "query",
                "list": "search",
                "srsearch": question,
                "format": "json",
                "utf8": "1",
                "srlimit": 3
            },

            headers={
                "User-Agent": "KingsBotAI/1.0"
            },

            timeout=8
        )

        response.raise_for_status()

        results = []

        search_results = response.json().get(
            "query",
            {}
        ).get(
            "search",
            []
        )


        for item in search_results:

            title = item.get("title")

            if not title:
                continue


            try:

                page = requests.get(
                    "https://en.wikipedia.org/api/rest_v1/page/summary/"
                    + requests.utils.quote(title),

                    headers={
                        "User-Agent": "KingsBotAI/1.0"
                    },

                    timeout=8
                )

                page.raise_for_status()

                summary = page.json().get(
                    "extract"
                )

                if summary:

                    results.append(
                        title
                        + ":\n"
                        + summary
                    )

            except Exception:
                continue


        if results:

            return "\n\n".join(
                results[:3]
            )


    except Exception:
        pass


    return None


