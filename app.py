# VOICE: SPEECH TO TEXT
# ============================================================

def speech_to_text(audio_file):

    try:

        recognizer = sr.Recognizer()

        audio_file.seek(0)

        with sr.AudioFile(
            audio_file
        ) as source:

            audio_data = recognizer.record(
                source
            )


        text = recognizer.recognize_google(
            audio_data,
            language="en-US"
        )

        return text


    except Exception:

        return None


# ============================================================
# VOICE: TEXT TO SPEECH
# ============================================================

def text_to_speech(text):

    try:

        audio = io.BytesIO()

        speech = gTTS(
            text=text[:3000],
            lang="en",
            slow=False
        )

        speech.write_to_fp(
            audio
        )

        audio.seek(0)

        return audio.getvalue()


    except Exception:

        return None


