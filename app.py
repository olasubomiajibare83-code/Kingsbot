def safe_calculate(expression):

    allowed = {

        ast.Add: operator.add,
        ast.Sub: operator.sub,
        ast.Mult: operator.mul,
        ast.Div: operator.truediv,
        ast.Pow: operator.pow,
        ast.Mod: operator.mod,
        ast.USub: operator.neg,
        ast.UAdd: operator.pos
    }


    functions = {

        "sqrt": math.sqrt,
        "sin": math.sin,
        "cos": math.cos,
        "tan": math.tan,
        "log": math.log,
        "pi": math.pi,
        "e": math.e
    }


    def evaluate(node):

        if isinstance(
            node,
            ast.Expression
        ):

            return evaluate(
                node.body
            )


        if (
            isinstance(
                node,
                ast.Constant
            )
            and isinstance(
                node.value,
                (int, float)
            )
        ):

            return node.value


        if (
            isinstance(
                node,
                ast.Name
            )
            and node.id in functions
        ):

            return functions[node.id]


        if (
            isinstance(
                node,
                ast.UnaryOp
            )
            and type(node.op) in allowed
        ):

            return allowed[
                type(node.op)
            ](
                evaluate(node.operand)
            )


        if (
            isinstance(
                node,
                ast.BinOp
            )
            and type(node.op) in allowed
        ):

            left = evaluate(
                node.left
            )

            right = evaluate(
                node.right
            )

            if (
                isinstance(
                    node.op,
                    ast.Pow
                )
                and abs(right) > 100
            ):

                raise ValueError(
                    "Exponent is too large."
                )

            return allowed[
                type(node.op)
            ](
                left,
                right
            )


        if (
            isinstance(
                node,
                ast.Call
            )
            and isinstance(
                node.func,
                ast.Name
            )
            and node.func.id in functions
        ):

            function = functions[
                node.func.id
            ]

            args = [
                evaluate(arg)
                for arg in node.args
            ]

            return function(*args)


        raise ValueError(
            "Unsupported expression."
        )


    tree = ast.parse(
        expression.strip(),
        mode="eval"
    )

    return evaluate(tree)


def extract_math_expression(text):

    low = text.lower().strip()

    if not any(
        word in low
        for word in [
            "calculate",
            "what is",
            "solve",
            "="
        ]
    ):

        return None


    cleaned = re.sub(
        r"^(calculate|solve|what is)\s+",
        "",
        low
    ).strip(" ?.")


    if re.fullmatch(
        r"[0-9+\-*/().,%\s^]+",
        cleaned
    ):

        return (
            cleaned
            .replace("^", "**")
            .replace("%", "/100")
        )


    return None


