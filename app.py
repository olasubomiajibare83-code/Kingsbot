def detect_emotion(text):
    lower = text.lower()

    groups = {
        "frustrated": [
            "angry",
            "mad",
            "annoyed",
            "frustrated",
            "you are wrong",
            "mistake",
            "this is wrong",
        ],
        "sad": ["sad", "crying", "upset", "hurt", "unhappy"],
        "confused": [
            "confused",
            "don't understand",
            "do not understand",
            "explain again",
            "i don't get it",
        ],
        "worried": [
            "worried",
            "scared",
            "afraid",
            "nervous",
            "anxious",
        ],
        "excited": [
            "excited",
            "amazing",
            "wow",
            "can't wait",
        ],
        "happy": [
            "happy",
            "great",
            "awesome",
            "thanks",
            "thank you",
            "yesss",
        ],
    }

    for emotion, words in groups.items():
        if any(word in lower for word in words):
            return emotion

    return "neutral"


