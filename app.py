def generate_response(user_message):
    detect_name(user_message)
    detect_student_level(user_message)
    remember_information(user_message)

    forgotten = forget_information(user_message)

    if forgotten:
        st.session_state.source = "KingsBot memory system"
        st.session_state.confidence = "High"
        st.session_state.reason = (
            "The user explicitly requested a memory change."
        )
        return forgotten

    emotion = detect_emotion(user_message)
    st.session_state.emotion = emotion

    tone_name, tone_instruction = tone_for(emotion)
    st.session_state.tone = tone_name

    topic = update_topic(user_message)

    retrieved = None

    if needs_current_lookup(user_message):
        retrieved = current_lookup(user_message)

    prompt = (
        "You are KingsBot, a fast, capable, helpful general-purpose AI assistant.\n\n"
        "CURRENT DATE:\n"
        + CURRENT_DATE
        + "\n\n"
        "CAPABILITIES:\n"
        "Answer broad questions about everyday life, general knowledge, "
        "science, mathematics, coding, programming, debugging, education, "
        "history, geography, technology, sports, entertainment, writing, "
        "planning, explanations, brainstorming, and problem solving.\n\n"
        "ACCURACY:\n"
        "Never knowingly invent facts. If you are uncertain, say so clearly. "
        "Do not pretend to have live information unless current information "
        "has been supplied.\n\n"
        "CODING:\n"
        "When asked to code, produce complete, syntactically valid code. "
        "Check imports, indentation, function definitions, dependencies, "
        "and likely runtime problems. Keep the user's requested features.\n\n"
        "MATHEMATICS:\n"
        "Calculate carefully. Show useful steps when appropriate and give "
        "the final answer clearly.\n\n"
        "EDUCATION:\n"
        + education_context()
        + "\n\n"
        "EMOTIONAL INTELLIGENCE:\n"
        "Detected emotion: "
        + emotion
        + ". "
        + tone_instruction
        + "\n\n"
        "TONE ADAPTATION:\n"
        "Use the selected tone naturally. Do not announce the tone repeatedly.\n\n"
        "CONVERSATION:\n"
        "Use recent conversation context when relevant. If the user changes "
        "topic, follow the new topic.\n\n"
        "PERSONAL MEMORY:\n"
        + memory_context()
        + "\n\n"
        "PROACTIVE HELP:\n"
        "When useful, ask one short follow-up question or suggest a useful "
        "next step. Do not ask unnecessary questions.\n\n"
        "REASONING:\n"
        "Think carefully internally, but do not reveal private chain-of-thought. "
        "Give the user the useful conclusion, calculations, or steps.\n\n"
        "STYLE:\n"
        "Be natural, friendly, direct, and concise for simple questions. "
        "For complex questions, provide enough detail to be genuinely useful."
    )

    if retrieved:
        prompt += (
            "\n\nCURRENT LOOKUP INFORMATION:\n"
            + retrieved
            + "\nUse this as supporting information only."
        )

    messages = [
        {
            "role": "system",
            "content": prompt,
        }
    ]

    messages.extend(
        st.session_state.messages[-10:]
    )

    messages.append(
        {
            "role": "user",
            "content": user_message,
        }
    )

    client = get_groq_client()

    completion = client.chat.completions.create(
        model=MODEL_NAME,
        messages=messages,
        temperature=0.5,
        top_p=0.9,
        max_completion_tokens=1200,
        stream=False,
    )

    response = (
        completion.choices[0]
        .message
        .content
        or ""
    ).strip()

    if not response:
        response = (
            "I couldn't generate an answer. "
            "Please try again."
        )

    if retrieved:
        st.session_state.source = (
            "Groq + current information lookup"
        )
        st.session_state.confidence = "Medium-High"
        st.session_state.reason = (
            "The answer used the Groq model and "
            "supporting current lookup information."
        )
    else:
        st.session_state.source = (
            "Groq " + MODEL_NAME
        )
        st.session_state.confidence = "Medium-High"
        st.session_state.reason = (
            "Generated by the Groq AI model using "
            "conversation context and KingsBot instructions."
        )

    return response


