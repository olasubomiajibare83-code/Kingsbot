def text_to_speech(text):
    if not has_token():
        return None


    try:
        response = requests.post(
            "https://router.huggingface.co/hf-inference/models/"
            + TTS_MODEL,
            headers=hf_headers(
                "application/json"
            ),
            json={
                "inputs": text[:2500]
            },
            timeout=120
        )

        response.raise_for_status()

        return response.content


    except Exception:
        return None


