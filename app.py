def get_tone_instruction(emotion):

    if emotion == "frustrated":

        return (
            "Be calm, respectful and direct. "
            "Do not argue with the user.",
            "Calm and direct"
        )


    if emotion == "sad":

        return (
            "Be warm, kind and supportive.",
            "Warm and supportive"
        )


    if emotion == "confused":

        return (
            "Use simple language and explain "
            "the answer step by step.",
            "Simple and step-by-step"
        )


    if emotion == "worried":

        return (
            "Be reassuring and give clear practical steps.",
            "Reassuring and practical"
        )


    if emotion == "happy":

        return (
            "Use a friendly and positive tone.",
            "Friendly and positive"
        )


    return (
        "Use a natural, friendly and clear tone.",
        "Natural and friendly"
    )


# ------------------------------------------------------------
# PATTERN RECOGNITION
# ------------------------------------------------------------

def detect_patterns():

    patterns = []


    user_messages = [

        message["content"].lower()

        for message in st.session_state.messages

        if message["role"] == "user"
    ]


    if len(user_messages) < 3:

        return patterns


    coding_count = sum(

        1

        for text in user_messages

        if (
            "code" in text
            or "python" in text
            or "app" in text
            or "coding" in text
        )
    )


    school_count = sum(

        1

        for text in user_messages

        if (
            "school" in text
            or "jss" in text
            or "ss1" in text
            or "ss2" in text
            or "ss3" in text
        )
    )


    if coding_count >= 2:

        patterns.append(
            "The user frequently asks about coding or apps."
        )


    if school_count >= 2:

        patterns.append(
            "The user frequently asks school-related questions."
        )


    return patterns


