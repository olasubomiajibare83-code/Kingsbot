def empty_memory():
    return {
        "name": None,
        "facts": [],
        "preferences": [],
        "education_level": None,
    }


def load_memory():
    memory = empty_memory()

    try:
        if os.path.exists(MEMORY_FILE):
            with open(
                MEMORY_FILE,
                "r",
                encoding="utf-8",
            ) as file:
                saved = json.load(file)

            if isinstance(saved, dict):
                for key in memory:
                    if key in saved:
                        memory[key] = saved[key]

    except Exception:
        pass

    return memory


def save_memory():
    data = {
        "name": st.session_state.name,
        "facts": st.session_state.facts[-100:],
        "preferences": st.session_state.preferences[-50:],
        "education_level": st.session_state.education_level,
    }

    try:
        with open(
            MEMORY_FILE,
            "w",
            encoding="utf-8",
        ) as file:
            json.dump(
                data,
                file,
                indent=2,
                ensure_ascii=False,
            )

    except Exception:
        pass


