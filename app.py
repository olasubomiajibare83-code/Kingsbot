def detect_emotion(text):

    lower = text.lower()


    if any(
        word in lower
        for word in [
            "angry",
            "mad",
            "annoyed",
            "frustrated",
            "you are wrong",
            "mistake"
        ]
    ):

        return "frustrated"


    if any(
        word in lower
        for word in [
            "sad",
            "crying",
            "upset",
            "hurt"
        ]
    ):

        return "sad"


    if any(
        word in lower
        for word in [
            "confused",
            "don't understand",
            "do not understand",
            "explain again"
        ]
    ):

        return "confused"


    if any(
        word in lower
        for word in [
            "worried",
            "scared",
            "afraid",
            "nervous"
        ]
    ):

        return "worried"


    if any(
        word in lower
        for word in [
            "happy",
            "great",
            "awesome",
            "thanks",
            "thank you",
            "yesss"
        ]
    ):

        return "happy"


    return "neutral"


