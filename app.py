def remember_information(text):
    name_match = re.search(
        r"\b(?:my name is|call me)\s+([A-Za-z][A-Za-z '\-]{1,39})",
        text,
        re.IGNORECASE
    )

    if name_match:
        st.session_state.name = (
            name_match.group(1).strip()
        )
        save_memory()


    fact_match = re.search(
        r"\b(?:remember that|remember this|save this)"
        r"\s*[:,-]?\s*(.+)",
        text,
        re.IGNORECASE
    )

    if fact_match:
        fact = fact_match.group(1).strip()

        if fact and fact not in st.session_state.facts:
            st.session_state.facts.append(fact)

        st.session_state.facts = (
            st.session_state.facts[-50:]
        )

        save_memory()

        return fact

    return None


