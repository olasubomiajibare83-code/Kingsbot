# ------------------------------------------------------------
# WEB LOOKUP
# ------------------------------------------------------------

def web_lookup(question):

    sources = []


    # --------------------------------------------------------
    # WIKIPEDIA SEARCH
    # --------------------------------------------------------

    try:

        search_response = requests.get(
            "https://en.wikipedia.org/w/api.php",

            params={
                "action": "query",
                "list": "search",
                "srsearch": question,
                "format": "json",
                "utf8": 1,
                "srlimit": 2
            },

            headers={
                "User-Agent": "KingsBotAI/1.0"
            },

            timeout=8
        )


        search_response.raise_for_status()

        search_data = search_response.json()


        results = (
            search_data
            .get("query", {})
            .get("search", [])
        )


        for result in results:

            title = result.get("title")

            if not title:
                continue


            try:

                page_response = requests.get(
                    "https://en.wikipedia.org/api/rest_v1/page/summary/"
                    + requests.utils.quote(title),

                    headers={
                        "User-Agent": "KingsBotAI/1.0"
                    },

                    timeout=8
                )


                page_response.raise_for_status()

                page_data = page_response.json()

                extract = page_data.get(
                    "extract"
                )


                if extract:

                    sources.append(
                        "Wikipedia - "
                        + title
                        + ":\n"
                        + extract
                    )


            except Exception:

                continue


    except Exception:

        pass


    # --------------------------------------------------------
    # DUCKDUCKGO INSTANT ANSWER
    # --------------------------------------------------------

    try:

        ddg_response = requests.get(
            "https://api.duckduckgo.com/",

            params={
                "q": question,
                "format": "json",
                "no_html": 1,
                "skip_disambig": 1
            },

            headers={
                "User-Agent": "KingsBotAI/1.0"
            },

            timeout=8
        )


        ddg_response.raise_for_status()

        ddg_data = ddg_response.json()


        abstract = ddg_data.get(
            "AbstractText"
        )


        if abstract:

            sources.append(
                "DuckDuckGo information:\n"
                + abstract
            )


    except Exception:

        pass


    if not sources:

        return None


    return "\n\n".join(
        sources[:4]
    )


