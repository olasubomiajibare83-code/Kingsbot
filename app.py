def conversation_file():
    lines = [
        "KINGSBOT AI CONVERSATION",
        "=" * 50,
        "Date: " + CURRENT_DATE,
        "",
    ]

    for message in st.session_state.messages:
        role = message.get(
            "role",
            "unknown",
        ).upper()

        content = message.get(
            "content",
            "",
        )

        lines.append(role + ":")
        lines.append(content)
        lines.append("")

    return "\n".join(lines)


