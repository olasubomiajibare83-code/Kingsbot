def clean_search_text(value):
    value = re.sub(
        r"<[^>]+>",
        " ",
        value,
    )

    value = html.unescape(value)

    value = re.sub(
        r"\s+",
        " ",
        value,
    )

    return value.strip()


def web_search(query):
    """
    Uses DuckDuckGo's public HTML search page.

    This is a real web lookup, not a hard-coded knowledge list.
    """

    try:
        response = requests.get(
            "https://html.duckduckgo.com/html/",
            params={
                "q": query,
            },
            headers={
                "User-Agent": (
                    "Mozilla/5.0 "
                    "(Windows NT 10.0; Win64; x64) "
                    "AppleWebKit/537.36 "
                    "Chrome/131 Safari/537.36"
                )
            },
            timeout=15,
        )

        response.raise_for_status()

        page = response.text

        result_pattern = re.compile(
            r'class="result__a"[^>]*href="([^"]+)"[^>]*>'
            r"(.*?)</a>",
            re.IGNORECASE | re.DOTALL,
        )

        snippets_pattern = re.compile(
            r'class="result__snippet"[^>]*>'
            r"(.*?)</(?:a|div)>",
            re.IGNORECASE | re.DOTALL,
        )

        links = result_pattern.findall(page)
        snippets = snippets_pattern.findall(page)

        results = []

        for index, item in enumerate(links[:6]):

            url = html.unescape(item[0])

            title = clean_search_text(
                item[1]
            )

            snippet = ""

            if index < len(snippets):
                snippet = clean_search_text(
                    snippets[index]
                )

            if title:
                results.append(
                    {
                        "title": title,
                        "url": url,
                        "snippet": snippet,
                    }
                )

        if not results:
            return None

        st.session_state.last_search = query

        return results

    except Exception:
        return None


def search_context(results):
    if not results:
        return ""

    lines = [
        "LIVE WEB SEARCH RESULTS:",
        "",
    ]

    for index, result in enumerate(results, 1):

        lines.append(
            f"{index}. {result['title']}"
        )

        lines.append(
            "URL: " + result["url"]
        )

        if result["snippet"]:
            lines.append(
                "Summary: " + result["snippet"]
            )

        lines.append("")

    return "\n".join(lines)


