# NAME MEMORY
# ============================================================

def detect_name(text):

    patterns = [
        r"\bmy name is ([A-Za-z][A-Za-z '\-]{1,40})",
        r"\bcall me ([A-Za-z][A-Za-z '\-]{1,40})",
        r"\byou can call me ([A-Za-z][A-Za-z '\-]{1,40})"
    ]

    for pattern in patterns:

        match = re.search(
            pattern,
            text,
            re.IGNORECASE
        )

        if match:

            name = match.group(1).strip()

            st.session_state.user_name = name

            return name

    return None


# ============================================================
# REMEMBER USER INFORMATION
# ============================================================

def remember_information(text):

    lower = text.lower()

    phrases = [
        "remember that",
        "remember this",
        "please remember",
        "keep this in mind"
    ]

    for phrase in phrases:

        if phrase in lower:

            position = lower.find(phrase)

            memory = text[
                position + len(phrase):
            ].strip(" :,-")

            if memory:

                if memory not in st.session_state.personal_memory:

                    st.session_state.personal_memory.append(
                        memory
                    )

                return memory

    return None


# ============================================================
# ETHICAL FORGETTING
# ============================================================

def handle_forgetting(text):

    lower = text.lower()

    if (
        "forget everything" in lower
        or "forget all my memory" in lower
        or "delete everything you remember" in lower
    ):

        st.session_state.user_name = None
        st.session_state.student_level = None
        st.session_state.personal_memory = []

        return (
            "Done. I cleared the personal information "
            "you asked me to forget."
        )

    if (
        "forget my name" in lower
        or "delete my name" in lower
    ):

        st.session_state.user_name = None

        return "Done. I forgot your saved name."

    if (
        "forget my class" in lower
        or "forget my education level" in lower
    ):

        st.session_state.student_level = None

        return (
            "Done. I forgot your saved education level."
        )

    return None


# ============================================================
# EMOTION DETECTION
# ============================================================

def detect_emotion(text):

    lower = text.lower()

    if any(
        word in lower
        for word in [
            "angry",
            "mad",
            "annoyed",
            "you are wrong",
            "useless"
        ]
    ):
        return "frustrated"

    if any(
        word in lower
        for word in [
            "sad",
            "crying",
            "upset",
            "hurt"
        ]
    ):
        return "sad"

    if any(
        word in lower
        for word in [
            "confused",
            "don't understand",
            "do not understand",
            "explain again"
        ]
    ):
        return "confused"

    if any(
        word in lower
        for word in [
            "worried",
            "scared",
            "afraid",
            "nervous"
        ]
    ):
        return "worried"

    if any(
        word in lower
        for word in [
            "happy",
            "great",
            "awesome",
            "good",
            "thanks",
            "thank you",
            "yesss"
        ]
    ):
        return "happy"

    return "neutral"


