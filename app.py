# CURRENT INFORMATION LOOKUP
# ============================================================

def current_information_search(question):

    results = []

    # --------------------------------------------------------
    # Wikipedia
    # --------------------------------------------------------

    try:

        response = requests.get(
            "https://en.wikipedia.org/w/api.php",
            params={
                "action": "query",
                "list": "search",
                "srsearch": question,
                "format": "json",
                "utf8": 1,
                "srlimit": 3
            },
            headers={
                "User-Agent": "KingsBotAI/1.0"
            },
            timeout=10
        )

        response.raise_for_status()

        data = response.json()

        search_results = (
            data
            .get("query", {})
            .get("search", [])
        )

        for item in search_results:

            title = item.get("title")

            if not title:
                continue

            try:

                page = requests.get(
                    "https://en.wikipedia.org/api/rest_v1/page/summary/"
                    + requests.utils.quote(title),
                    headers={
                        "User-Agent": "KingsBotAI/1.0"
                    },
                    timeout=10
                )

                page.raise_for_status()

                page_data = page.json()

                extract = page_data.get(
                    "extract"
                )

                if extract:

                    results.append(
                        "Wikipedia - "
                        + title
                        + ":\n"
                        + extract
                    )

            except Exception:

                continue

    except Exception:

        pass

    # --------------------------------------------------------
    # DuckDuckGo Instant Answer
    # --------------------------------------------------------

    try:

        response = requests.get(
            "https://api.duckduckgo.com/",
            params={
                "q": question,
                "format": "json",
                "no_html": 1,
                "skip_disambig": 1
            },
            headers={
                "User-Agent": "KingsBotAI/1.0"
            },
            timeout=10
        )

        response.raise_for_status()

        data = response.json()

        abstract = data.get(
            "AbstractText"
        )

        if abstract:

            results.append(
                "DuckDuckGo:\n"
                + abstract
            )

    except Exception:

        pass

    if not results:

        return None

    return "\n\n".join(
        results[:5]
    )


