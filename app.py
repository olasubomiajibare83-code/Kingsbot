# ============================================================
# PATTERN RECOGNITION
# ============================================================

def detect_patterns():

    user_messages = [
        message["content"].lower()
        for message in st.session_state.messages
        if message["role"] == "user"
    ]

    patterns = []

    if len(user_messages) < 3:

        return patterns

    coding_count = sum(
        1
        for text in user_messages
        if (
            "code" in text
            or "coding" in text
            or "python" in text
            or "app" in text
        )
    )

    school_count = sum(
        1
        for text in user_messages
        if (
            "school" in text
            or "jss" in text
            or "ss1" in text
            or "ss2" in text
            or "ss3" in text
        )
    )

    if coding_count >= 2:

        patterns.append(
            "The user frequently asks about coding or apps."
        )

    if school_count >= 2:

        patterns.append(
            "The user frequently asks school questions."
        )

    return patterns


