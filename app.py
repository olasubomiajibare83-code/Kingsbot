def ask_real_ai(user_text, web_results=None):
    if not token_available():
        st.session_state.source = (
            "AI unavailable"
        )

        st.session_state.confidence = (
            "Unavailable"
        )

        st.session_state.reason = (
            "HF_TOKEN is missing."
        )

        return (
            "KingsBot is ready, but the real AI brain "
            "cannot connect because HF_TOKEN is missing "
            "from your Hugging Face Space Secrets."
        )

    context = search_context(
        web_results
    )

    messages = [
        {
            "role": "system",
            "content": build_system_prompt(
                context
            ),
        }
    ]

    messages.extend(
        st.session_state.messages[-20:]
    )

    messages.append(
        {
            "role": "user",
            "content": user_text,
        }
    )

    payload = {
        "model": AI_MODEL,
        "messages": messages,
        "temperature": 0.6,
        "max_tokens": 1400,
        "stream": False,
    }

    try:
        response = requests.post(
            HF_CHAT_URL,
            headers=auth_headers(
                "application/json"
            ),
            json=payload,
            timeout=180,
        )

        response.raise_for_status()

        data = response.json()

        choices = data.get(
            "choices",
            []
        )

        if not choices:
            raise RuntimeError(
                "The AI provider returned no choices."
            )

        message = choices[0].get(
            "message",
            {}
        )

        answer = message.get(
            "content",
            ""
        )

        if isinstance(answer, list):

            parts = []

            for item in answer:

                if isinstance(item, dict):

                    text = item.get(
                        "text",
                        ""
                    )

                    if text:
                        parts.append(text)

            answer = "\n".join(parts)

        answer = str(
            answer
        ).strip()

        if not answer:
            raise RuntimeError(
                "The AI provider returned an empty answer."
            )

        if web_results:
            st.session_state.source = (
                "Real LLM + live web search"
            )
        else:
            st.session_state.source = (
                "Real LLM + conversation memory"
            )

        st.session_state.confidence = (
            "Model-dependent"
        )

        st.session_state.reason = (
            "Generated by the real language model."
        )

        return answer

    except requests.exceptions.Timeout:

        st.session_state.confidence = "Low"

        st.session_state.reason = (
            "The AI request timed out."
        )

        return (
            "The real AI model took too long to respond. "
            "Please try again."
        )

    except requests.exceptions.HTTPError:

        st.session_state.confidence = "Low"

        st.session_state.reason = (
            "Hugging Face returned an HTTP error."
        )

        try:
            error_data = response.json()
            error_text = json.dumps(
                error_data,
                indent=2,
            )
        except Exception:
            error_text = response.text

        return (
            "The real AI brain could not complete "
            "the request.\n\n"
            + error_text
        )

    except Exception as error:

        st.session_state.confidence = "Low"

        st.session_state.reason = (
            "The AI request failed."
        )

        return (
            "The real AI brain encountered an error:\n\n"
            + str(error)
        )


